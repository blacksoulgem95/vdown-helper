// The desktop window's stylesheet holds every utility, not only the ones Tailwind finds in the sources (VDH-088): on
// the desktop the size does not matter and nothing is downloaded again. This writes the candidates as an
// `@source inline(...)` file, which desktop/ui/src/styles.css imports. Tailwind's own design system lists them, for the
// installed version and this theme.
//
// Every utility with every variant is not possible (the combinations are unbounded; all utilities with ten variants
// are already 63 MB), so the list is:
// - every utility Tailwind knows, with its theme values;
// - the theme's colours (and white/black) at every opacity step, for the colour utilities;
// - the interactive states on the main colour utilities and on a few effect utilities.
// Anything else the code uses (arbitrary values, other variants) still comes from the scan of the sources.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
// the API Tailwind's editor tooling uses to list classes; pinned by package-lock, and checked below
import { __unstable__loadDesignSystem as loadDesignSystem } from 'tailwindcss';

const require = createRequire(import.meta.url);

/** Tailwind's stylesheets (`@import 'tailwindcss'` and its parts), for the design system. */
async function loadStylesheet(id) {
  const dir = dirname(require.resolve('tailwindcss/package.json'));
  const path =
    id === 'tailwindcss'
      ? resolve(dir, 'index.css')
      : resolve(dir, `${id.replace(/^tailwindcss\//, '')}.css`);
  return { path, base: dirname(path), content: readFileSync(path, 'utf8') };
}

const COLOR_UTILITIES = [
  'bg',
  'text',
  'border',
  'border-t',
  'border-b',
  'border-l',
  'border-r',
  'border-x',
  'border-y',
  'ring',
  'outline',
  'shadow',
  'divide',
  'from',
  'via',
  'to',
  'fill',
  'stroke',
  'placeholder',
  'decoration',
  'caret',
  'accent',
];
const STATE_UTILITIES = ['bg', 'text', 'border', 'ring', 'outline', 'shadow'];
const STATES = [
  'hover',
  'focus',
  'focus-visible',
  'active',
  'disabled',
  'group-hover',
  'aria-selected',
  'aria-pressed',
];
const EFFECTS = /^(opacity-|underline$|no-underline$|cursor-|scale-\d|translate-[xy]-\d|brightness-)/;
const steps = (by) => Array.from({ length: 100 / by + 1 }, (_, i) => i * by);

/**
 * Writes `out` (an `@source inline(...)` file) for the theme at `themePath`, and returns Tailwind's own list of its
 * utilities (the build checks they all made it into the CSS).
 */
export async function writeAllUtilities(themePath, out) {
  // the theme without its @source: only the design system is wanted here
  const theme = readFileSync(themePath, 'utf8').replace(/@source\s[^;]*;/g, '');
  const ds = await loadDesignSystem(theme, { base: dirname(themePath), loadStylesheet });
  const utilities = ds.getClassList().map(([name]) => name);
  if (utilities.length < 10_000) throw new Error(`Tailwind listed only ${utilities.length} utilities`);
  const palette = [...theme.matchAll(/--color-([\w-]+):/g)].map((m) => m[1]).concat('white', 'black');
  const shades = (fns, by) =>
    fns.flatMap((u) => palette.flatMap((c) => [`${u}-${c}`, ...steps(by).map((s) => `${u}-${c}/${s}`)]));
  const states = [...shades(STATE_UTILITIES, 10), ...utilities.filter((u) => EFFECTS.test(u))];
  const all = new Set([
    ...utilities,
    ...shades(COLOR_UTILITIES, 5),
    ...STATES.flatMap((s) => states.map((u) => `${s}:${u}`)),
  ]);
  // nothing in the list may close the string or the at-rule
  for (const c of all) if (/["\\;\s]/.test(c)) throw new Error(`unexpected candidate ${JSON.stringify(c)}`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(
    out,
    '/* Generated by scripts/desktop/tailwind-all.mjs for the desktop window: do not edit. */\n' +
      `@source inline("${[...all].join(' ')}");\n`,
  );
  return utilities;
}
