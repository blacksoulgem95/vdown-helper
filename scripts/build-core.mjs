// Builds the Rust core (core/, core-wasm/) to WebAssembly for the extension: src/wasm/gen/ (generated, not committed).
//   - core.js / core.d.ts: wasm-bindgen glue (--target web)
//   - bytes.ts: the .wasm inlined as base64, so every context (service worker, offscreen, pages, tests) can
//     instantiate it synchronously without fetching anything.
// Needs: rustup target wasm32-unknown-unknown and the wasm-bindgen CLI at the version pinned in core-wasm/Cargo.toml.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const out = resolve(root, 'src/wasm/gen');
const run = (cmd, args) =>
  execFileSync(cmd, args, { cwd: root, stdio: ['ignore', 'pipe', 'inherit'] }).toString();

const pinned = /wasm-bindgen = "=([\d.]+)"/.exec(
  readFileSync(resolve(root, 'core-wasm/Cargo.toml'), 'utf8'),
)?.[1];
let cli;
try {
  cli = /([\d.]+)/.exec(run('wasm-bindgen', ['--version']))?.[1];
} catch {
  cli = undefined;
}
if (cli !== pinned) {
  console.error(
    `wasm-bindgen CLI ${cli ?? 'not found'}; the core needs ${pinned}: cargo install wasm-bindgen-cli --version ${pinned} --locked`,
  );
  process.exit(1);
}

run('cargo', [
  'build',
  '--profile',
  'wasm',
  '--locked',
  '--target',
  'wasm32-unknown-unknown',
  '-p',
  'vdh-core-wasm',
]);
const wasm = resolve(root, 'target/wasm32-unknown-unknown/wasm/vdh_core_wasm.wasm');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
run('wasm-bindgen', [
  '--target',
  'web',
  '--no-typescript',
  '--omit-default-module-path',
  '--out-dir',
  out,
  '--out-name',
  'core',
  wasm,
]);
run('wasm-bindgen', [
  '--target',
  'web',
  '--omit-default-module-path',
  '--out-dir',
  resolve(out, 'types'),
  '--out-name',
  'core',
  wasm,
]);
renameSync(resolve(out, 'types/core.d.ts'), resolve(out, 'core.d.ts'));
const bytes = readFileSync(resolve(out, 'core_bg.wasm'));
rmSync(resolve(out, 'types'), { recursive: true, force: true });
rmSync(resolve(out, 'core_bg.wasm'));
writeFileSync(
  resolve(out, 'bytes.ts'),
  `// Generated by scripts/build-core.mjs: vdh-core as WebAssembly (${bytes.length} bytes), base64.\nexport const CORE_WASM_BASE64 =\n  '${bytes.toString('base64')}';\n`,
);
console.log(`vdh-core wasm: ${(bytes.length / 1024).toFixed(0)} KB -> src/wasm/gen`);
